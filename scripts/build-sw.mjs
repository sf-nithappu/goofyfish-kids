// Writes sw.js with an offline cache list of every game, shared file, thumbnail and icon.
import { readdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const list = async (dir) => (await readdir(dir).catch(() => [])).filter((f) => !f.startsWith('.')).map((f) => `${dir}/${f}`);
const files = ['./', 'index.html', 'games.json', 'manifest.webmanifest', ...(await list('shared')), ...(await list('games')), ...(await list('fonts')), ...(await list('thumbs')), ...(await list('icons'))];
const hash = createHash('sha1');
for (const f of files) {
  if (f !== './') {
    hash.update(await readFile(f));
  }
}
const v = hash.digest('hex').slice(0, 10);
await writeFile('sw.js', `// generated by scripts/build-sw.mjs, do not edit
const CACHE = 'gk-${v}';
const FILES = ${JSON.stringify(files, null, 2)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('gk-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);
console.log(`sw.js: ${files.length} files, cache gk-${v}`);
